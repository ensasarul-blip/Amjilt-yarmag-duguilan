-- ---------------------------------------------------------------------
-- Түр туслах функц (файлын төгсгөлд устгана)
--   sessions : [{"d":гараг,"s":"эхлэх","e":"дуусах"}]
--              хоосон [] бол "цаг тодорхойгүй"
-- ---------------------------------------------------------------------
create or replace function public.__seed_club(
  p_name     text,
  p_level    text,
  p_grades   smallint[],
  p_room     text,
  p_teacher  text,
  p_capacity integer,
  p_sessions jsonb
)
returns void
language plpgsql
as $$
declare
  v_id    uuid;
  v_order integer;
  s       jsonb;
begin
  select coalesce(max(sort_order), 0) + 10 into v_order from public.clubs;

  insert into public.clubs (name, level, grades, room, teacher, capacity, sort_order)
  values (p_name, p_level, p_grades, p_room, p_teacher, p_capacity, v_order)
  returning id into v_id;

  if jsonb_array_length(p_sessions) = 0 then
    insert into public.club_sessions (club_id, weekday, start_time, end_time, note)
    values (v_id, null, null, null, 'Цаг тодорхойгүй');
  else
    for s in select * from jsonb_array_elements(p_sessions) loop
      insert into public.club_sessions (club_id, weekday, start_time, end_time)
      values (v_id, (s->>'d')::smallint, (s->>'s')::time, (s->>'e')::time);
    end loop;
  end if;
end
$$;

